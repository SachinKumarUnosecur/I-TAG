function cvssToImpactLikelihood(cvss) {
  if (cvss >= 9) return { impact: 5, likelihood: 5 };
  if (cvss >= 8) return { impact: 5, likelihood: 4 };
  if (cvss >= 7) return { impact: 4, likelihood: 4 };
  if (cvss >= 5.5) return { impact: 3, likelihood: 3 };
  if (cvss >= 4) return { impact: 3, likelihood: 2 };
  return { impact: 2, likelihood: 2 };
}

